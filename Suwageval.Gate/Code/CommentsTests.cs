using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Suwageval.Gate.Code;

public sealed partial class CommentsTests
{
    private const string Fix =
        "delete it, rename the code so it explains itself, move the task to TODO.md, or write `// Why: <reason>` if the code looks wrong without it.";

    // Why: the SDK's XML documentation ships in its NuGet package, and the contracts' becomes the OpenAPI descriptions of the published API
    private static readonly string[] DocumentedProjects = ["Suwageval.AgentSdk", "Suwageval.Contracts"];

    private sealed record Comment(int Line, string Text, bool IsDocumentation);

    [GeneratedRegex(@"\b(TODO|FIXME|HACK|workaround|temporary)\b", RegexOptions.IgnoreCase)]
    private static partial Regex Marker();

    [GeneratedRegex(@"^// Why: \S.*$")]
    private static partial Regex Why();

    [GeneratedRegex(@"^/\*lang=\w+\*/$")]
    private static partial Regex LanguageMarker();

    [GeneratedRegex(@"^// </?auto-generated>$")]
    private static partial Regex GeneratedMarker();

    [Fact]
    public void Every_comment_is_a_Why_or_a_tool_marker_and_none_is_a_task_or_dead_code()
    {
        var problems = SourceFile
            .All.SelectMany(file => CommentsIn(file).Select(comment => (file.Path, comment, Problem: Problem(file.Path, comment))))
            .Where(found => found.Problem is not null)
            .Select(found => $"{found.Path}:{found.comment.Line}: {found.Problem}: {found.comment.Text}")
            .ToList();

        Assert.True(problems.Count == 0, $"{Fix}{Environment.NewLine}{string.Join(Environment.NewLine, problems)}");
    }

    [Theory]
    [InlineData("// Why: the pool is dropped first, grate reconnects", null)]
    [InlineData("/*lang=json*/", null)]
    [InlineData("// <auto-generated>", null)]
    [InlineData("// Why: do it later (TODO)", "a task marker")]
    [InlineData("// the clock", "not a Why")]
    [InlineData("// Why:", "not a Why")]
    [InlineData("// var x = 1;", "not a Why")]
    [InlineData("// Why: x = 1;", "commented-out code")]
    [InlineData("/// <summary>x</summary>", "XML documentation outside the SDK and the contracts")]
    [InlineData("// temporary fix", "a task marker")]
    public void The_rules_judge_a_comment(string text, string? expected)
    {
        var comment = CommentsIn(new SourceFile("Suwageval.Server/X.cs", text + "\nclass X;")).Single();

        Assert.Equal(expected, Problem("Suwageval.Server/X.cs", comment));
    }

    [Fact]
    public void Documentation_is_allowed_in_the_SDK_and_the_contracts()
    {
        var comment = CommentsIn(new SourceFile("Suwageval.Contracts/X.cs", "/// <summary>x</summary>\nclass X;")).Single();

        Assert.Null(Problem("Suwageval.Contracts/X.cs", comment));
    }

    [Fact]
    public void Comment_signs_inside_strings_are_not_comments()
    {
        var source = "var a = \"http://x\"; var b = @\"// no\"; var c = \"\"\"\n// no\n\"\"\"; var d = '\"'; // Why: yes";

        var comments = CommentsIn(new SourceFile("X.cs", source));

        Assert.Equal(["// Why: yes"], comments.Select(comment => comment.Text));
    }

    private static IEnumerable<Comment> CommentsIn(SourceFile file) =>
        file
            .Root.DescendantTrivia()
            .Where(trivia =>
                trivia.Kind()
                    is SyntaxKind.SingleLineCommentTrivia
                        or SyntaxKind.MultiLineCommentTrivia
                        or SyntaxKind.SingleLineDocumentationCommentTrivia
                        or SyntaxKind.MultiLineDocumentationCommentTrivia
            )
            .Select(trivia => new Comment(
                trivia.GetLocation().GetLineSpan().StartLinePosition.Line + 1,
                trivia.ToString().Trim(),
                trivia.Kind() is SyntaxKind.SingleLineDocumentationCommentTrivia or SyntaxKind.MultiLineDocumentationCommentTrivia
            ));

    private static string? Problem(string path, Comment comment)
    {
        if (comment.IsDocumentation)
        {
            return DocumentedProjects.Contains(path.Split('/')[0]) ? null : "XML documentation outside the SDK and the contracts";
        }
        if (LanguageMarker().IsMatch(comment.Text) || GeneratedMarker().IsMatch(comment.Text))
        {
            return null;
        }
        if (Marker().IsMatch(comment.Text))
        {
            return "a task marker";
        }
        if (!Why().IsMatch(comment.Text))
        {
            return "not a Why";
        }
        return comment.Text.EndsWith(';') || comment.Text.EndsWith('{') || comment.Text.EndsWith('}') ? "commented-out code" : null;
    }
}
